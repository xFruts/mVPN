CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_telegram_id BIGINT,
    full_name VARCHAR(255) NOT NULL UNIQUE,
    verification_code UUID,
    role VARCHAR(50) NOT NULL,
    xui_id UUID,
    xui_subscription UUID
);

CREATE TABLE servers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255),
    location VARCHAR(255),
    ip VARCHAR(255),
    status SMALLINT,
    load INTEGER,
    usage INTEGER,
    max_users INTEGER,
    max_traffic INTEGER,
    ping VARCHAR(255),
    uptime DOUBLE PRECISION,
    country_emoji VARCHAR(255),
    login VARCHAR(255),
    password VARCHAR(255),
    ssh_auth_type VARCHAR(50),
    ssh_private_key_object_key VARCHAR(255),
    subscription_format VARCHAR(50),
    xui_login VARCHAR(255),
    xui_password VARCHAR(255),
    xui_auth_token VARCHAR(255),
    port INTEGER,
    web_base_path VARCHAR(255),
    successful_checks BIGINT,
    failed_checks BIGINT,
    host_key TEXT
);

CREATE TABLE tariff_plan (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL UNIQUE,
    max_devices INTEGER NOT NULL,
    traffic_limit_gb INTEGER NOT NULL,
    duration_of_days INTEGER NOT NULL
);

CREATE TABLE tariff_plan_servers (
    tariff_id BIGINT NOT NULL,
    server_id BIGINT NOT NULL,
    PRIMARY KEY (tariff_id, server_id),
    CONSTRAINT fk7ssljuvxcwumk19xfnx81lrfn FOREIGN KEY (server_id) REFERENCES servers(id),
    CONSTRAINT fk_tariff_servers_tariff FOREIGN KEY (tariff_id) REFERENCES tariff_plan(id)
);

CREATE TABLE subscriptions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    start_date TIMESTAMP WITH TIME ZONE NOT NULL,
    end_date TIMESTAMP WITH TIME ZONE NOT NULL,
    status VARCHAR(50) NOT NULL,
    tariff_id BIGINT NOT NULL,
    CONSTRAINT fk_subscription_user FOREIGN KEY (user_id) REFERENCES users(id),
    CONSTRAINT fk_subscription_tariff FOREIGN KEY (tariff_id) REFERENCES tariff_plan(id)
);

CREATE TABLE promo_codes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(255) NOT NULL UNIQUE,
    expiration_date TIMESTAMP WITH TIME ZONE NOT NULL,
    tariff_id BIGINT NOT NULL,
    usage_limit INTEGER DEFAULT 1 NOT NULL,
    usage INTEGER DEFAULT 0 NOT NULL,
    status SMALLINT NOT NULL,
    CONSTRAINT fk_promocode_tariff FOREIGN KEY (tariff_id) REFERENCES tariff_plan(id)
);

CREATE TABLE broadcasts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message VARCHAR(255),
    target_audience TINYINT,
    custom_user_ids BIGINT ARRAY
);

CREATE TABLE users_settings (
    keycloak_user_id VARCHAR(255) PRIMARY KEY,
    theme VARCHAR(255) NOT NULL
);

CREATE TABLE payment_settings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    billing_month VARCHAR(7) NOT NULL,
    expected_amount NUMERIC(19, 2) NOT NULL,
    bank_name VARCHAR(100) NOT NULL,
    requisites VARCHAR(500) NOT NULL,
    created_by BIGINT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_payment_settings_month_creator UNIQUE (billing_month, created_by)
);

CREATE TABLE payment_verifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paid_until_date VARCHAR(10) NOT NULL,
    user_id BIGINT NOT NULL,
    payer_full_name VARCHAR(200) NOT NULL,
    paid_amount NUMERIC(19, 2) NOT NULL,
    currency VARCHAR(3) NOT NULL,
    status VARCHAR(50) NOT NULL,
    user_comment VARCHAR(1000),
    admin_comment VARCHAR(1000),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    verified_at TIMESTAMP WITH TIME ZONE,
    verified_by BIGINT,
    CONSTRAINT uk_paid_until_user UNIQUE (paid_until_date, user_id),
    CONSTRAINT fk_payment_verification_user FOREIGN KEY (user_id) REFERENCES users(id)
);
